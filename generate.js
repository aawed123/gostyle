// Generates src/_scale-utilities.css  (numbered utility classes)
// Change the numbers/values below, then run: npm run build
const fs = require("fs"), path = require("path");

const SPACE_MAX = 16;   // p-0 ... p-16  (16 x 4px = 64px)
const RADIUS_MAX = 10;  // b-radius-0 ... b-radius-10
const sp = (n) => `calc(var(--gs-space-unit) * ${n})`;

let css = "/* AUTO-GENERATED by generate.js - edit generate.js, not this file */\n";
const rule = (sel, decl) => (css += `.gs-${sel} { ${decl} }\n`);

// Padding & margin: p, pt, pr, pb, pl, px, py  (same for m)
const sides = {
  "": ["{p}"],
  t: ["{p}-top"], r: ["{p}-right"], b: ["{p}-bottom"], l: ["{p}-left"],
  x: ["{p}-left", "{p}-right"], y: ["{p}-top", "{p}-bottom"],
};
for (const [short, prop] of [["p", "padding"], ["m", "margin"]]) {
  for (const [side, props] of Object.entries(sides)) {
    for (let n = 0; n <= SPACE_MAX; n++) {
      rule(`${short}${side}-${n}`, props.map(x => `${x.replace("{p}", prop)}: ${sp(n)};`).join(" "));
    }
  }
}
// margin auto helpers
rule("m-auto", "margin: auto;");
rule("mx-auto", "margin-left: auto; margin-right: auto;");
rule("my-auto", "margin-top: auto; margin-bottom: auto;");

// Gap
for (let n = 0; n <= SPACE_MAX; n++) rule(`gap-${n}`, `gap: ${sp(n)};`);

// Border radius: b-radius-1 = 4px, 2 = 8px, 3 = 12px ...
for (let n = 0; n <= RADIUS_MAX; n++)
  rule(`b-radius-${n}`, `border-radius: calc(var(--gs-radius-unit) * ${n});`);
rule("b-radius-full", "border-radius: 9999px;");

// Border width: b-width-1 = 1px ... 4 = 4px (also sets solid style)
for (let n = 0; n <= 4; n++)
  rule(`b-width-${n}`, `border-width: ${n}px; border-style: ${n ? "solid" : "none"};`);

// Font size: fs-1 ... fs-8
const fs_ = [0.75, 0.875, 1, 1.125, 1.25, 1.5, 1.875, 2.25];
fs_.forEach((v, i) => rule(`fs-${i + 1}`, `font-size: ${v}rem;`));

// Font weight: fw-1 (300) ... fw-5 (700)
[300, 400, 500, 600, 700].forEach((v, i) => rule(`fw-${i + 1}`, `font-weight: ${v};`));

// Width & height (percent)
for (const p of [25, 50, 75, 100]) {
  rule(`w-${p}`, `width: ${p}%;`);
  rule(`h-${p}`, `height: ${p}%;`);
}
rule("w-auto", "width: auto;");
rule("h-auto", "height: auto;");

// Colors: text, background, border color
const colors = ["primary", "secondary", "success", "danger", "info", "warning", "light", "dark"];
colors.forEach((c) => {
  rule(`text-${c}`, `color: var(--gs-${c});`);
  rule(`bg-${c}`, `background-color: var(--gs-${c});`);
  rule(`b-color-${c}`, `border-color: var(--gs-${c});`);
});
rule("text-muted", "color: var(--gs-muted);");
rule("text-white", "color: #fff;");
rule("bg-gradient", "background: var(--gs-gradient);");
rule("text-gradient", "background: var(--gs-gradient); -webkit-background-clip: text; background-clip: text; -webkit-text-fill-color: transparent; color: transparent;");
rule("bg-white", "background-color: #fff;");

// Shadows: shadow-0 ... shadow-3
rule("shadow-0", "box-shadow: none;");
rule("shadow-1", "box-shadow: var(--gs-shadow-sm);");
rule("shadow-2", "box-shadow: var(--gs-shadow-md);");
rule("shadow-3", "box-shadow: var(--gs-shadow-lg);");

// Auto margins on one side
rule("ml-auto", "margin-left: auto;");
rule("mr-auto", "margin-right: auto;");

fs.writeFileSync(path.join(__dirname, "src", "_scale-utilities.css"), css);
console.log("Generated src/_scale-utilities.css");

/* ------------------------------------------------------------------
   12-column responsive grid  ->  src/_grid-columns.css
   Breakpoints (mobile-first, min-width): sm 576, md 768, lg 992, xl 1200
   Classes: gs-col-N, gs-col-md-N, gs-col, gs-col-md, gs-col-auto,
            gs-offset-N, gs-offset-md-N
------------------------------------------------------------------ */
const COLS = 12;
const BREAKPOINTS = { sm: 576, md: 768, lg: 992, xl: 1200 };
const pct = (n) => `${+((n / COLS) * 100).toFixed(6)}%`;
const tiers = [["", null], ...Object.entries(BREAKPOINTS)];   // "" = all screens

// shared padding for every column class
const all = [];
tiers.forEach(([bp]) => {
  const mid = bp ? `-${bp}` : "";
  all.push(`.gs-col${mid}`, `.gs-col${mid}-auto`);
  for (let n = 1; n <= COLS; n++) all.push(`.gs-col${mid}-${n}`);
});
let grid = "/* AUTO-GENERATED by generate.js - edit generate.js, not this file */\n";
grid += `${all.join(",\n")} { position: relative; width: 100%; padding: 0 .5rem; }\n`;

tiers.forEach(([bp, min]) => {
  const mid = bp ? `-${bp}` : "";
  let block = "";
  block += `.gs-col${mid} { flex: 1 0 0; max-width: 100%; }\n`;
  block += `.gs-col${mid}-auto { flex: 0 0 auto; width: auto; max-width: 100%; }\n`;
  for (let n = 1; n <= COLS; n++)
    block += `.gs-col${mid}-${n} { flex: 0 0 ${pct(n)}; max-width: ${pct(n)}; }\n`;
  for (let n = 0; n < COLS; n++)
    block += `.gs-offset${mid}-${n} { margin-left: ${n ? pct(n) : "0"}; }\n`;
  grid += min ? `@media (min-width: ${min}px) {\n${block}}\n` : block;
});

fs.writeFileSync(path.join(__dirname, "src", "_grid-columns.css"), grid);
console.log("Generated src/_grid-columns.css");
